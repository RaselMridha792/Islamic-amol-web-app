import fs from 'node:fs';
import path from 'node:path';
import { globalAyah } from '../lib/quranMeta.js';

const ROOT = process.cwd();
const chapters = {};
function ayahOf(s, a) {
  if (!chapters[s]) {
    chapters[s] = JSON.parse(fs.readFileSync(path.join(ROOT, 'public/quran', s + '.json'), 'utf8'));
  }
  const v = chapters[s].verses[a - 1];
  if (!v || v.id !== a) throw new Error(`আয়াত নেই: ${s}:${a}`);
  return v;
}

