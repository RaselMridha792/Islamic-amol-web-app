/* ---------- যাচাই ও লেখা ---------- */

const AR_RUN = /[؀-ۿݐ-ݿࢠ-ࣿ]+(?:\s+[؀-ۿݐ-ݿࢠ-ࣿ]+)*/g;
const order = CATS.map((c) => c.id);
const seen = new Set();
const problems = [];

const out = LESSONS.map((l) => {
  if (seen.has(l.id)) problems.push('একই আইডি দুবার: ' + l.id);
  seen.add(l.id);
  if (!order.includes(l.cat)) problems.push('অজানা শ্রেণি: ' + l.cat + ' (' + l.id + ')');

  const examples = (l.examples || []).map((ex) => {
    const v = ayahOf(ex.s, ex.a);
    const words = v.text.split(' ');
    const where = `${l.id} → ${ex.s}:${ex.a}`;
    (ex.hi || []).forEach((n) => {
      if (!Number.isInteger(n) || n < 1 || n > words.length) {
        problems.push(`${where}: ${n} নম্বর শব্দ নেই (আয়াতে ${words.length}টা)`);
      }
    });
    // ব্যাখ্যার আরবি হুবহু আয়াতে থাকতে হবে। ডেটায় তাশদীদ আগে, হরকত পরে
    // লেখা; কিবোর্ডে উল্টোটা আসে — দেখতে একই, তাই দুদিকই NFC করে মেলাই।
    const plain = v.text.normalize('NFC');
    (ex.note.match(AR_RUN) || []).forEach((run) => {
      if (!plain.includes(run.normalize('NFC'))) problems.push(`${where}: ব্যাখ্যার “${run}” আয়াতে হুবহু নেই`);
    });
    return {
      s: ex.s,
      a: ex.a,
      ar: v.text,
      bn: v.translation,
      hi: ex.hi || [],
      note: ex.note,
      audio: globalAyah(ex.s, ex.a),
    };
  });

  const item = { id: l.id, cat: l.cat, title: l.title, sub: l.sub, body: l.body };
  if (l.points) item.points = l.points;
  if (l.voice) item.voice = l.voice;
  item.examples = examples;
  return item;
});

const emptyCat = CATS.filter((c) => !out.some((l) => l.cat === c.id));
if (emptyCat.length) problems.push('ফাঁকা শ্রেণি: ' + emptyCat.map((c) => c.id).join(', '));

if (problems.length) {
  console.error(problems.join('\n'));
  process.exit(1);
}

