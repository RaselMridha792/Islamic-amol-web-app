import fs from 'node:fs';
import path from 'node:path';
import { toBanglaUccharon } from '../lib/uccharon.js';
import { globalAyah } from '../lib/quranMeta.js';
import { surahBn } from '../lib/content/surahNames.js';

const ROOT = process.cwd();
const chapters = {};
function ch(n) {
  if (!chapters[n]) {
    chapters[n] = JSON.parse(fs.readFileSync(path.join(ROOT, 'public/quran', n + '.json'), 'utf8'));
  }
  return chapters[n];
}

function fromQuran(surah, from, to = from) {
  const c = ch(surah);
  const vs = c.verses.filter((v) => v.id >= from && v.id <= to);
  if (vs.length !== to - from + 1) throw new Error(`missing ayah ${surah}:${from}-${to}`);
  return {
    ar: vs.map((v) => v.text).join(' '),
    tr: vs.map((v) => toBanglaUccharon(v.text, surah, v.id)).join(' '),
    bn: vs.map((v) => v.translation).join(' '),
    ref: `সুরা ${surahBn(surah)} ${from}${to !== from ? '-' + to : ''}`,
    audio: vs.map((v) => globalAyah(surah, v.id)),
  };
}

// কিছু দোয়া আয়াতের একটা অংশ মাত্র — যেমন "রব্বি জিদনী ইলমা" সুরা ত্বা-হার
// ১১৪ নম্বর আয়াতের শেষ তিন শব্দ। বারবার পড়ার জন্য পুরো আয়াতটা দেখানো ভুল
// হতো, তাই যাচাই করা লেখা থেকে ঠিক শব্দগুলোই কেটে নিই। অর্থটাও ওই আয়াতের
// অনুবাদের ভেতর থেকেই নেওয়া।
function sliceOfAyah(surah, ayah, fromWord, toWord, bnPart) {
  const v = ch(surah).verses.find((x) => x.id === ayah);
  if (!v) throw new Error(`missing ${surah}:${ayah}`);
  const words = v.text.split(/\s+/).filter(Boolean);
  const ar = words.slice(fromWord, toWord + 1).join(' ');
  if (!ar) throw new Error(`empty slice ${surah}:${ayah}`);
  return {
    ar,
    tr: toBanglaUccharon(ar),
    bn: bnPart,
    ref: `সুরা ${surahBn(surah)} ${ayah} (অংশ)`,
    audio: [],
  };
}

