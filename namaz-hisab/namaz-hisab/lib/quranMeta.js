// এই সুরাটা কোন কোন পারায় ছড়ানো
export function juzSpanOf(surah) {
  const s = SURAHS[surah - 1];
  return { from: juzOf(surah, 1), to: juzOf(surah, s.ayahs) };
}

// এই পারায় কোন কোন সুরা, আর প্রতিটির কোন আয়াত থেকে কোন আয়াত।
// একটা পারা সুরার মাঝখানে শুরু বা শেষ হতে পারে, তাই টুকরোটাও বলে দিই।
export function juzParts(juz) {
  const r = JUZ_RANGE[juz - 1];
  const out = [];
  SURAHS.forEach((s) => {
    const start = globalAyah(s.id, 1);
    const end = globalAyah(s.id, s.ayahs);
    if (end < r.from || start > r.to) return;
    out.push({
      id: s.id,
      from: Math.max(r.from, start) - start + 1,
      to: Math.min(r.to, end) - start + 1,
      whole: start >= r.from && end <= r.to,
    });
  });
  return out;
}

// সুরার ভেতরে যে আয়াতগুলোতে নতুন পারা শুরু হয়
export function juzBreaksIn(surah) {
  return JUZ_START.map(([su, ay], i) => (su === surah && !(su === 1 && ay === 1) ? { ayah: ay, juz: i + 1 } : null))
    .filter(Boolean);
}
