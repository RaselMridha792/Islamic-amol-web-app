// পারা n এর আয়াতগুলো বিশ্বজোড়া নম্বরে কোথা থেকে কোথায়
export const JUZ_RANGE = JUZ_START.map((start, i) => {
  const from = globalAyah(start[0], start[1]);
  const next = JUZ_START[i + 1];
  const to = next ? globalAyah(next[0], next[1]) - 1 : TOTAL_AYAHS;
  return { juz: i + 1, from, to, count: to - from + 1 };
});

export function juzOf(surah, ayah) {
  const g = globalAyah(surah, ayah);
  for (let i = JUZ_RANGE.length - 1; i >= 0; i -= 1) {
    if (g >= JUZ_RANGE[i].from) return i + 1;
  }
  return 1;
}

