export const TOTAL_AYAHS = 6236;

// প্রতিটি সুরার আগে কয়টা আয়াত পেরিয়ে এসেছি — বিশ্বজোড়া নম্বর বের করতে
const OFFSET = (() => {
  const out = [0];
  let run = 0;
  SURAHS.forEach((s) => { run += s.ayahs; out.push(run); });
  return out;
})();

export function globalAyah(surah, ayah) {
  return OFFSET[surah - 1] + ayah;
}

